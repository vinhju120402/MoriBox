// Generates supabase/seed.sql from app/data/products.ts.
// Usage: node scripts/generate-seed.mjs
import { writeFileSync } from 'node:fs';
import { PRODUCTS } from '../app/data/products.ts';

const q = v => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = a => `array[${(a ?? []).map(q).join(',')}]::text[]`;

const rows = PRODUCTS.map((p, i) => `(${[
  q(p.id), q(p.name), q(p.grade), q(p.scale), q(p.series),
  p.price, p.salePrice ?? 'null', q(p.image), arr(p.images),
  p.stock, p.isNew, p.isBestSeller,
  `${q(JSON.stringify(p.specs))}::jsonb`, q(p.description),
  // Spread timestamps so the catalog keeps its original order (sorted by created_at).
  `now() + interval '${i} seconds'`,
].join(', ')})`);

const sql = `-- Seed data generated by scripts/generate-seed.mjs — do not edit by hand.
-- Run in the Supabase SQL Editor AFTER schema.sql. Safe to re-run (upserts by id,
-- but re-running resets stock/price of these products to the seed values).
insert into public.products
  (id, name, grade, scale, series, price, sale_price, image, images, stock, is_new, is_best_seller, specs, description, created_at)
values
${rows.join(',\n')}
on conflict (id) do update set
  name = excluded.name, grade = excluded.grade, scale = excluded.scale, series = excluded.series,
  price = excluded.price, sale_price = excluded.sale_price, image = excluded.image, images = excluded.images,
  stock = excluded.stock, is_new = excluded.is_new, is_best_seller = excluded.is_best_seller,
  specs = excluded.specs, description = excluded.description;
`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`Wrote supabase/seed.sql with ${PRODUCTS.length} products`);
